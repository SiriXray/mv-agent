import {loadPlaywright} from './playwright-runtime.mjs';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createApp, ROOT} from '../server.mjs';
import {run, binaries} from '../lib/media.mjs';

const {chromium} = loadPlaywright();
await fs.mkdir(path.join(ROOT, 'artifacts'), {recursive: true});
const data = await fs.mkdtemp(path.join(os.tmpdir(), 'mv-ai-browser-test-'));
const imageFile = path.join(data, 'reference.png'), audioFile = path.join(data, 'song.wav');
await run(binaries().ffmpeg, ['-nostdin', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc=size=512x512', '-frames:v', '1', imageFile]);
await run(binaries().ffmpeg, ['-nostdin', '-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=20:sample_rate=48000', audioFile]);
const originalHash = createHash('sha256').update(await fs.readFile(imageFile)).digest('hex');
const calls = [], errors = [];
const caption = '彩色测试图案位于正方形画面中，竖向色条与网格排列清楚，中心标记醒目，背景光线均匀。';
const app = createApp({dataDir: data, env: {}, aiOptions: {fetchImpl: async (url, request) => {
  const body = JSON.parse(request.body); calls.push({url, body});
  assert.equal(url, 'https://mock-gateway.example.com/v1/responses');
  let result;
  if (body.input[1].content.some(c => c.type === 'input_image')) result = {asset_name: '彩色测试图案', asset_description: caption, type: 'scene'};
  else {
    const input = JSON.parse(body.input[1].content[0].text);
    result = {COT: '模拟 LLM 创作的叙事：从城市色彩走向宁静夜景。', shots: [7, 13].map((duration, i) => ({duration, scene: i ? '近景逐渐拉远，主体停在灯下，城市的色彩渐渐收束。' : '远景缓缓推进，主体穿过彩色灯光，开启夜晚的旅程。', assets: [input.assets[0].asset_id]}))};
  }
  return Response.json({status: 'completed', output: [{type: 'message', content: [{type: 'output_text', text: JSON.stringify(result)}]}], usage: {input_tokens: 10, output_tokens: 20}});
}}});
await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${app.server.address().port}`, artifacts = path.join(ROOT, 'artifacts');
const browser = await chromium.launch({headless: true});
try {
  const page = await browser.newPage({viewport: {width: 1500, height: 1050}});
  page.on('pageerror', e => errors.push(e.message)); page.on('dialog', dialog => dialog.accept());
  await page.goto(base); await page.locator('[data-view="ai"]').waitFor();
  await page.locator('[data-view="studio"]').click(); await page.locator('[data-field="title"]').waitFor();
  assert.equal(await page.locator('[data-field="planner"]').inputValue(), 'llm');
  assert.equal(await page.locator('[data-field="generationDuration"]').inputValue(),'15');
  assert.equal(await page.locator('[data-field="resolution"]').inputValue(),'2K');
  await page.locator('[data-view="ai"]').click(); await page.locator('#ai-config-form').waitFor();
  await page.locator('[name="planner.url"]').fill('https://mock-gateway.example.com/v1/responses');
  await page.locator('[name="planner.model"]').fill('gpt-fixture');
  await page.locator('[name="planner.protocol"]').selectOption('responses');
  await page.locator('[name="planner.apiKey"]').fill('fixture-browser-secret');
  await page.locator('[data-action="save-ai"]').click();
  await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('配置已保存'));
  assert.equal(calls.length, 0); assert.equal(await page.locator('[name="planner.apiKey"]').inputValue(), '');
  assert.ok(!(await page.content()).includes('fixture-browser-secret'));
  await page.screenshot({path: path.join(artifacts, 'ai-config-desktop.png'), fullPage: true});
  await page.locator('[data-view="studio"]').click(); await page.locator('[data-upload="image"]').setInputFiles(imageFile);
  await page.waitForFunction(text => document.querySelector('.asset-description')?.textContent === text, caption, {timeout: 30000});
  assert.equal(calls.length, 1); assert.equal(await page.locator('.asset-edit').getAttribute('open'), null);
  assert.equal(await page.locator('[data-asset="0"][data-key="asset_description"]').inputValue(), caption);
  await page.locator('[data-upload="audio"]').setInputFiles(audioFile);
  await page.waitForFunction(() => document.querySelector('audio') && !document.body.classList.contains('busy'), {}, {timeout: 30000});
  await page.locator('[data-field="prompt"]').fill('一个从喧闹城市走向安静灯下的故事。');
  await page.locator('[data-field="lyrics"]').fill('00:00:02,000 --> 00:00:07,000\n穿过城市的光\n\n00:00:09,000 --> 00:00:17,000\n在灯下轻轻停留');
  await page.screenshot({path: path.join(artifacts, 'ai-assets-desktop.png'), fullPage: true});
  await page.locator('[data-action="plan"]').click(); await page.locator('.storyboard').first().waitFor({timeout: 30000});
  assert.equal(calls.length, 2); assert.equal(await page.locator('.storyboard').count(), 2);
  assert.equal(await page.locator('[data-shot="0"][data-key="duration"]').inputValue(), '7');
  assert.equal(await page.locator('[data-shot="1"][data-key="duration"]').inputValue(), '13');
  assert.equal(await page.locator('[data-shot="1"][data-key="duration"]').getAttribute('max'), '15');
  assert.match(await page.locator('.section-toolbar').innerText(), /20 秒剪辑时间/);
  assert.ok((await page.locator('[data-shot="0"][data-key="prompt"]').inputValue()).includes(caption));
  await page.screenshot({path: path.join(artifacts, 'ai-storyboard-desktop.png'), fullPage: true});
  await page.locator('[data-view="ai"]').click(); await page.locator('#ai-preset').selectOption('deepseek');
  assert.equal(await page.locator('[name="planner.url"]').inputValue(), 'https://api.deepseek.com/chat/completions');
  assert.equal(await page.locator('#vision-reuse').isChecked(), false);
  assert.equal(await page.locator('[name="vision.model"]').inputValue(), 'gpt-fixture');
  await page.locator('[name="planner.apiKey"]').fill('fixture-deepseek-secret');
  await page.locator('[data-action="save-ai"]').click();
  await page.waitForFunction(() => !document.body.classList.contains('busy'));
  const boot = await (await fetch(base + '/api/bootstrap')).json();
  assert.equal(boot.ai.planner.protocol, 'chat'); assert.equal(boot.ai.vision.protocol, 'responses');
  assert.equal(boot.ai.vision.configured, true); assert.equal(calls.length, 2);
  assert.ok(!(await page.content()).includes('fixture-deepseek-secret'));
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: path.join(artifacts, 'ai-config-mobile.png'), fullPage: true});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'AI configuration mobile overflow');
  await page.locator('[data-view="studio"]').click(); await page.locator('[data-step="1"]').click();
  await page.screenshot({path: path.join(artifacts, 'ai-storyboard-mobile.png'), fullPage: true});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Storyboard mobile overflow');
  await page.locator('[data-step="0"]').click();
  await page.screenshot({path: path.join(artifacts, 'ai-assets-mobile.png'), fullPage: true});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Asset UI mobile overflow');
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
  assert.equal(createHash('sha256').update(await fs.readFile(imageFile)).digest('hex'), originalHash);
  assert.deepEqual(errors, []);
  const result = {status: 'passed', date: new Date().toISOString(), realModelRequests: 0, mockedModelRequests: calls.length, checks: ['configuration without model invocation', 'masked server-side credentials', 'automatic image descriptions without manual text', 'original image retained', 'LLM variable scene lengths (7s/13s) with SRT and 15s upstream', 'separate GPT vision with DeepSeek text configuration', 'desktop and 390px mobile', 'no browser runtime errors']};
  await fs.writeFile(path.join(artifacts, 'browser-ai-test-results.json'), JSON.stringify(result, null, 2)); console.log(JSON.stringify(result, null, 2));
} finally {
  await browser.close(); app.server.closeAllConnections(); await new Promise(resolve => app.server.close(resolve));
  assert.ok(path.resolve(data).startsWith(path.resolve(os.tmpdir()) + path.sep)); assert.ok(path.basename(data).startsWith('mv-ai-browser-test-')); await fs.rm(data, {recursive: true, force: true});
}
